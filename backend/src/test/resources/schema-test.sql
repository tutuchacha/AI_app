-- 测试库：H2 PostgreSQL 兼容模式（无 pgvector，检索走 app.rag.vector-store=memory）
CREATE TABLE IF NOT EXISTS sys_user
(
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(32)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    nickname      VARCHAR(32)  NOT NULL DEFAULT '',
    role          VARCHAR(16)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_user_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS conversation
(
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    uid             VARCHAR(32) NOT NULL DEFAULT '',
    user_id         BIGINT      NOT NULL,
    module          VARCHAR(16) NOT NULL DEFAULT 'chat',
    persona_id      BIGINT      NULL,
    kb_id           BIGINT      NULL,
    title           VARCHAR(64) NOT NULL DEFAULT '',
    model_id        BIGINT      NULL,
    last_message_at TIMESTAMP   NULL,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_conv_uid UNIQUE (uid)
);

CREATE TABLE IF NOT EXISTS message
(
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    conversation_id BIGINT      NOT NULL,
    role            VARCHAR(16) NOT NULL,
    content         TEXT        NOT NULL,
    tokens_in       INT         NOT NULL DEFAULT 0,
    tokens_out      INT         NOT NULL DEFAULT 0,
    latency_ms      INT         NOT NULL DEFAULT 0,
    model           VARCHAR(64) NOT NULL DEFAULT '',
    status          VARCHAR(16) NOT NULL DEFAULT 'DONE',
    request_id      VARCHAR(64) NULL,
    citation_json   TEXT        NULL,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS knowledge_base
(
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT       NOT NULL,
    name            VARCHAR(64)  NOT NULL,
    description     VARCHAR(255) NOT NULL DEFAULT '',
    embedding_model VARCHAR(64)  NOT NULL DEFAULT 'text-embedding-v3',
    chunk_size      INT          NOT NULL DEFAULT 800,
    chunk_overlap   INT          NOT NULL DEFAULT 120,
    document_count  INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS document
(
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    kb_id       BIGINT       NOT NULL,
    filename    VARCHAR(255) NOT NULL,
    ext         VARCHAR(16)  NOT NULL DEFAULT '',
    size        BIGINT       NOT NULL DEFAULT 0,
    sha256      CHAR(64)     NOT NULL DEFAULT '',
    status      VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    chunk_count INT          NOT NULL DEFAULT 0,
    error_msg   VARCHAR(500) NOT NULL DEFAULT '',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS document_chunk
(
    id            BIGINT    GENERATED BY DEFAULT AS IDENTITY,
    document_id   BIGINT    NOT NULL,
    kb_id         BIGINT    NOT NULL,
    chunk_index   INT       NOT NULL,
    content       TEXT      NOT NULL,
    embedding     TEXT      NULL,
    token_count   INT       NOT NULL DEFAULT 0,
    metadata_json TEXT      NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS document_analysis
(
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    document_id       BIGINT       NOT NULL,
    kb_id             BIGINT       NOT NULL,
    analysis_type     VARCHAR(16)  NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    content           TEXT         NULL,
    model             VARCHAR(64)  NOT NULL DEFAULT '',
    prompt_tokens     INT          NOT NULL DEFAULT 0,
    completion_tokens INT          NOT NULL DEFAULT 0,
    latency_ms        INT          NOT NULL DEFAULT 0,
    error_msg         VARCHAR(500) NOT NULL DEFAULT '',
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS support_ticket
(
    id               BIGINT           GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT           NOT NULL,
    conversation_uid VARCHAR(64)      NOT NULL DEFAULT '',
    kb_id            BIGINT           NULL,
    question         VARCHAR(500)     NOT NULL,
    best_score       DOUBLE PRECISION NOT NULL DEFAULT 0,
    status           VARCHAR(16)      NOT NULL DEFAULT 'OPEN',
    note             VARCHAR(500)     NOT NULL DEFAULT '',
    created_at       TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS date_profile
(
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT        NOT NULL,
    nickname    VARCHAR(40)   NOT NULL DEFAULT '',
    gender      VARCHAR(16)   NOT NULL DEFAULT '',
    age         INT           NULL,
    city        VARCHAR(40)   NOT NULL DEFAULT '',
    occupation  VARCHAR(60)   NOT NULL DEFAULT '',
    hobbies     VARCHAR(500)  NOT NULL DEFAULT '',
    personality VARCHAR(500)  NOT NULL DEFAULT '',
    goal        VARCHAR(500)  NOT NULL DEFAULT '',
    notes       VARCHAR(1000) NOT NULL DEFAULT '',
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS date_target
(
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT        NOT NULL,
    name            VARCHAR(40)   NOT NULL,
    channel         VARCHAR(60)   NOT NULL DEFAULT '',
    stage           VARCHAR(16)   NOT NULL DEFAULT 'MET',
    age             INT           NULL,
    city            VARCHAR(40)   NOT NULL DEFAULT '',
    interests       VARCHAR(500)  NOT NULL DEFAULT '',
    taboos          VARCHAR(500)  NOT NULL DEFAULT '',
    notes           VARCHAR(1000) NOT NULL DEFAULT '',
    last_contact_at DATE          NULL,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS date_advice
(
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT       NOT NULL,
    target_id         BIGINT       NOT NULL,
    stage             VARCHAR(16)  NOT NULL,
    city              VARCHAR(40)  NOT NULL DEFAULT '',
    goal              VARCHAR(500) NOT NULL DEFAULT '',
    content           TEXT         NOT NULL,
    spots             TEXT         NOT NULL DEFAULT '',
    model             VARCHAR(64)  NOT NULL DEFAULT '',
    prompt_tokens     INT          NOT NULL DEFAULT 0,
    completion_tokens INT          NOT NULL DEFAULT 0,
    latency_ms        INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS date_action
(
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    target_id  BIGINT       NOT NULL,
    advice_id  BIGINT       NULL,
    title      VARCHAR(120) NOT NULL,
    detail     VARCHAR(500) NOT NULL DEFAULT '',
    planned_at DATE         NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'PLANNED',
    result     VARCHAR(16)  NOT NULL DEFAULT 'UNKNOWN',
    note       VARCHAR(500) NOT NULL DEFAULT '',
    done_at    TIMESTAMP    NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);
