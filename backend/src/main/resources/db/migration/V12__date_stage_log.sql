-- D-05 恋爱助手：阶段变更记录，时间线里能看到「什么时候从哪一步走到哪一步」
CREATE TABLE IF NOT EXISTS date_stage_log
(
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    target_id  BIGINT      NOT NULL,
    from_stage VARCHAR(16) NOT NULL,
    to_stage   VARCHAR(16) NOT NULL,
    source     VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stage_log_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_stage_log_target FOREIGN KEY (target_id) REFERENCES date_target (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_stage_log_target ON date_stage_log (target_id, id DESC);

COMMENT ON TABLE date_stage_log IS '恋爱助手：阶段变更流水，供时间线展示';
COMMENT ON COLUMN date_stage_log.source IS 'MANUAL 手动修改 / REVIEW 复盘建议后应用';
