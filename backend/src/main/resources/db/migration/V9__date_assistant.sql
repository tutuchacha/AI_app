-- D-01 恋爱助手：我的档案 + 目标对象档案（一人一份档案，可多个对象）
CREATE TABLE IF NOT EXISTS date_profile
(
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL,
    nickname    VARCHAR(40)   NOT NULL DEFAULT '',
    gender      VARCHAR(16)   NOT NULL DEFAULT '',
    age         INT           NULL,
    city        VARCHAR(40)   NOT NULL DEFAULT '',
    occupation  VARCHAR(60)   NOT NULL DEFAULT '',
    hobbies     VARCHAR(500)  NOT NULL DEFAULT '',
    personality VARCHAR(500)  NOT NULL DEFAULT '',
    goal        VARCHAR(500)  NOT NULL DEFAULT '',
    notes       VARCHAR(1000) NOT NULL DEFAULT '',
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_date_profile_user UNIQUE (user_id),
    CONSTRAINT fk_date_profile_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

COMMENT ON TABLE date_profile IS '恋爱助手：我的档案';
COMMENT ON COLUMN date_profile.goal IS '期望的关系目标与节奏';
COMMENT ON COLUMN date_profile.notes IS '补充说明，AI 组提示词时一并带上';

CREATE TRIGGER trg_date_profile_updated_at
    BEFORE UPDATE
    ON date_profile
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS date_target
(
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    name            VARCHAR(40)   NOT NULL,
    channel         VARCHAR(60)   NOT NULL DEFAULT '',
    stage           VARCHAR(16)   NOT NULL DEFAULT 'MET',
    age             INT           NULL,
    city            VARCHAR(40)   NOT NULL DEFAULT '',
    interests       VARCHAR(500)  NOT NULL DEFAULT '',
    taboos          VARCHAR(500)  NOT NULL DEFAULT '',
    notes           VARCHAR(1000) NOT NULL DEFAULT '',
    last_contact_at DATE          NULL,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_date_target_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_date_target_user ON date_target (user_id, id DESC);

COMMENT ON TABLE date_target IS '恋爱助手：目标对象档案';
COMMENT ON COLUMN date_target.channel IS '认识途径：同事 / 朋友介绍 / 社交软件 等';
COMMENT ON COLUMN date_target.stage IS 'MET / CHATTING / INVITED / DATING / TOGETHER / PAUSED';
COMMENT ON COLUMN date_target.taboos IS '雷点：不要聊的话题、忌讳';

CREATE TRIGGER trg_date_target_updated_at
    BEFORE UPDATE
    ON date_target
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();
