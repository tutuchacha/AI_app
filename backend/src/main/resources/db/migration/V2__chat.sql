-- M1-01 会话与消息表
CREATE TABLE IF NOT EXISTS conversation
(
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL,
    module          VARCHAR(16) NOT NULL DEFAULT 'chat',
    persona_id      BIGINT      NULL,
    kb_id           BIGINT      NULL,
    title           VARCHAR(64) NOT NULL DEFAULT '',
    model_id        BIGINT      NULL,
    last_message_at TIMESTAMP   NULL,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conv_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_conv_user_module ON conversation (user_id, module, last_message_at);

COMMENT ON TABLE conversation IS '会话表';
COMMENT ON COLUMN conversation.module IS '业务模块：chat / companion / support / analysis';
COMMENT ON COLUMN conversation.title IS '会话标题，首条用户消息截断 30 字';
COMMENT ON COLUMN conversation.last_message_at IS '最后一条消息时间，用于列表排序';

CREATE TRIGGER trg_conversation_updated_at
    BEFORE UPDATE
    ON conversation
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS message
(
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL,
    role            VARCHAR(16) NOT NULL,
    content         TEXT        NOT NULL,
    tokens_in       INT         NOT NULL DEFAULT 0,
    tokens_out      INT         NOT NULL DEFAULT 0,
    latency_ms      INT         NOT NULL DEFAULT 0,
    model           VARCHAR(64) NOT NULL DEFAULT '',
    status          VARCHAR(16) NOT NULL DEFAULT 'DONE',
    request_id      VARCHAR(64) NULL,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_msg_conv FOREIGN KEY (conversation_id) REFERENCES conversation (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_msg_conv ON message (conversation_id, id);

COMMENT ON TABLE message IS '消息表';
COMMENT ON COLUMN message.content IS '消息内容，流式结束后为完整文本';
COMMENT ON COLUMN message.status IS 'STREAMING / DONE / STOPPED / FAILED';
COMMENT ON COLUMN message.request_id IS '本次生成请求 ID，便于重试与日志关联';
