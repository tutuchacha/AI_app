-- M2-01 RAG 知识库与文档表
-- 向量落 PostgreSQL + pgvector：embedding 仍存 JSON 文本（写入代码不变），
-- 生成列 embedding_vec 由它自动转换，检索走 HNSW + 余弦距离 <=>。
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS knowledge_base
(
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    name            VARCHAR(64)  NOT NULL,
    description     VARCHAR(255) NOT NULL DEFAULT '',
    embedding_model VARCHAR(64)  NOT NULL DEFAULT 'text-embedding-v3',
    chunk_size      INT          NOT NULL DEFAULT 800,
    chunk_overlap   INT          NOT NULL DEFAULT 120,
    document_count  INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_kb_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_kb_user ON knowledge_base (user_id, id);

COMMENT ON TABLE knowledge_base IS '知识库';
COMMENT ON COLUMN knowledge_base.embedding_model IS '向量模型，变更需重建索引';
COMMENT ON COLUMN knowledge_base.document_count IS '文档数（冗余统计，随文档增删维护）';

CREATE TRIGGER trg_knowledge_base_updated_at
    BEFORE UPDATE
    ON knowledge_base
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS document
(
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id       BIGINT       NOT NULL,
    filename    VARCHAR(255) NOT NULL,
    ext         VARCHAR(16)  NOT NULL DEFAULT '',
    size        BIGINT       NOT NULL DEFAULT 0,
    sha256      CHAR(64)     NOT NULL DEFAULT '',
    status      VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    chunk_count INT          NOT NULL DEFAULT 0,
    error_msg   VARCHAR(500) NOT NULL DEFAULT '',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_doc_kb FOREIGN KEY (kb_id) REFERENCES knowledge_base (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_doc_kb ON document (kb_id, id);
CREATE INDEX IF NOT EXISTS idx_doc_sha ON document (kb_id, sha256);

COMMENT ON TABLE document IS '知识库文档';
COMMENT ON COLUMN document.ext IS '扩展名：pdf / docx / txt / md';
COMMENT ON COLUMN document.sha256 IS '内容摘要，同库去重用';
COMMENT ON COLUMN document.status IS 'PENDING / PARSING / INDEXING / READY / FAILED';

CREATE TRIGGER trg_document_updated_at
    BEFORE UPDATE
    ON document
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS document_chunk
(
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   BIGINT  NOT NULL,
    kb_id         BIGINT  NOT NULL,
    chunk_index   INT     NOT NULL,
    content       TEXT    NOT NULL,
    embedding     TEXT    NULL,
    embedding_vec vector(1024) GENERATED ALWAYS AS (embedding::vector(1024)) STORED,
    token_count   INT     NOT NULL DEFAULT 0,
    metadata_json TEXT    NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chunk_doc FOREIGN KEY (document_id) REFERENCES document (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_chunk_kb ON document_chunk (kb_id, document_id);
CREATE INDEX IF NOT EXISTS idx_chunk_doc ON document_chunk (document_id, chunk_index);

-- 部分索引：未回填向量的切片不进索引，检索按余弦距离排序
CREATE INDEX IF NOT EXISTS idx_chunk_vec ON document_chunk
    USING hnsw (embedding_vec vector_cosine_ops)
    WHERE embedding_vec IS NOT NULL;

COMMENT ON TABLE document_chunk IS '文档切片';
COMMENT ON COLUMN document_chunk.embedding IS '向量 JSON 数组，未索引时为 NULL';
COMMENT ON COLUMN document_chunk.embedding_vec IS 'pgvector 生成列，由 embedding 自动转换，检索用';
COMMENT ON COLUMN document_chunk.metadata_json IS '页码、标题等来源信息';
