-- M3-01 文档分析任务：摘要 / 结构抽取 / 追问
-- 结果直接存 Markdown，前端用轻量渲染；按文档删记录走外键级联。
CREATE TABLE IF NOT EXISTS document_analysis
(
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       BIGINT       NOT NULL,
    kb_id             BIGINT       NOT NULL,
    analysis_type     VARCHAR(16)  NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    content           TEXT         NULL,
    model             VARCHAR(64)  NOT NULL DEFAULT '',
    prompt_tokens     INT          NOT NULL DEFAULT 0,
    completion_tokens INT          NOT NULL DEFAULT 0,
    latency_ms        INT          NOT NULL DEFAULT 0,
    error_msg         VARCHAR(500) NOT NULL DEFAULT '',
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_analysis_doc FOREIGN KEY (document_id) REFERENCES document (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_analysis_doc ON document_analysis (document_id, id);
CREATE INDEX IF NOT EXISTS idx_analysis_doc_type ON document_analysis (document_id, analysis_type, id);

COMMENT ON TABLE document_analysis IS '文档分析任务';
COMMENT ON COLUMN document_analysis.analysis_type IS 'SUMMARY / OUTLINE / QUESTIONS';
COMMENT ON COLUMN document_analysis.status IS 'PENDING / RUNNING / READY / FAILED';
COMMENT ON COLUMN document_analysis.content IS 'Markdown 结果';

CREATE TRIGGER trg_document_analysis_updated_at
    BEFORE UPDATE
    ON document_analysis
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();
