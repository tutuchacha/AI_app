-- M4-04 转人工工单：兜底触发时落一条记录，人工处理完置 CLOSED
CREATE TABLE IF NOT EXISTS support_ticket
(
    id               BIGINT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT           NOT NULL,
    conversation_uid VARCHAR(64)      NOT NULL DEFAULT '',
    kb_id            BIGINT           NULL,
    question         VARCHAR(500)     NOT NULL,
    best_score       DOUBLE PRECISION NOT NULL DEFAULT 0,
    status           VARCHAR(16)      NOT NULL DEFAULT 'OPEN',
    note             VARCHAR(500)     NOT NULL DEFAULT '',
    created_at       TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ticket_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ticket_user ON support_ticket (user_id, id DESC);

COMMENT ON TABLE support_ticket IS '转人工工单';
COMMENT ON COLUMN support_ticket.conversation_uid IS '触发兜底的会话 UID，只留痕不建外键';
COMMENT ON COLUMN support_ticket.best_score IS '触发兜底时的最高引用分，0~1';
COMMENT ON COLUMN support_ticket.status IS 'OPEN / CLOSED';
COMMENT ON COLUMN support_ticket.note IS '处理备注，前端可选填';

CREATE TRIGGER trg_support_ticket_updated_at
    BEFORE UPDATE
    ON support_ticket
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();
