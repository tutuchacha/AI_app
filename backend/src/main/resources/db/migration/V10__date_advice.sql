-- D-02 恋爱助手：每次 AI 建议落一条，供历史回看与 D-03 复盘对比
CREATE TABLE IF NOT EXISTS date_advice
(
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    target_id         BIGINT       NOT NULL,
    stage             VARCHAR(16)  NOT NULL,
    city              VARCHAR(40)  NOT NULL DEFAULT '',
    goal              VARCHAR(500) NOT NULL DEFAULT '',
    content           TEXT         NOT NULL,
    spots             TEXT         NOT NULL DEFAULT '',
    model             VARCHAR(64)  NOT NULL DEFAULT '',
    prompt_tokens     INT          NOT NULL DEFAULT 0,
    completion_tokens INT          NOT NULL DEFAULT 0,
    latency_ms        INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_advice_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_advice_target FOREIGN KEY (target_id) REFERENCES date_target (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_advice_target ON date_advice (target_id, id DESC);

COMMENT ON TABLE date_advice IS '恋爱助手：AI 阶段建议（结构化 JSON + 高德地点）';
COMMENT ON COLUMN date_advice.stage IS '出建议时的关系阶段快照';
COMMENT ON COLUMN date_advice.content IS '目标 / 动作 / 话术 / 禁忌 / 成功判断 的 JSON';
COMMENT ON COLUMN date_advice.spots IS '高德 POI 推荐 JSON，查询失败时为空数组';
