-- D-04 恋爱助手：执行记录 + 反馈，复盘时按最近几条判断继续 / 换策略 / 降速
CREATE TABLE IF NOT EXISTS date_action
(
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    target_id  BIGINT       NOT NULL,
    advice_id  BIGINT       NULL,
    title      VARCHAR(120) NOT NULL,
    detail     VARCHAR(500) NOT NULL DEFAULT '',
    planned_at DATE         NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'PLANNED',
    result     VARCHAR(16)  NOT NULL DEFAULT 'UNKNOWN',
    note       VARCHAR(500) NOT NULL DEFAULT '',
    done_at    TIMESTAMP    NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_action_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_action_target FOREIGN KEY (target_id) REFERENCES date_target (id) ON DELETE CASCADE,
    CONSTRAINT fk_action_advice FOREIGN KEY (advice_id) REFERENCES date_advice (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_action_target ON date_action (target_id, id DESC);

COMMENT ON TABLE date_action IS '恋爱助手：执行记录（做没做）与反馈（对方反应）';
COMMENT ON COLUMN date_action.status IS 'PLANNED 计划 / DONE 已完成 / SKIPPED 跳过';
COMMENT ON COLUMN date_action.result IS 'UNKNOWN 未回填 / GOOD 好 / NEUTRAL 一般 / COLD 冷淡 / NO_REPLY 未回复';
COMMENT ON COLUMN date_action.note IS '用户观察到的细节，复盘提示词会带上';
